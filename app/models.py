"""
app/models.py

SQLAlchemy database models for LegalGPT.

Defines the following tables:
    - User               : registered application users (and admins)
    - Document            : uploaded PDF/DOCX documents (for RAG)
    - ChatHistory          : AI chat question/answer history
    - GeneratedDocument    : AI-generated legal PDF documents
    - Advocate             : advocate directory for search feature

All models use Flask-SQLAlchemy's `db` instance defined in app/__init__.py.
"""

from datetime import datetime

from flask_login import UserMixin
from werkzeug.security import generate_password_hash, check_password_hash

from app import db


class User(UserMixin, db.Model):
    """
    Represents a registered user of the LegalGPT platform.

    Attributes:
        id (int): Primary key.
        username (str): Unique username used for login/display.
        email (str): Unique email address.
        password_hash (str): Securely hashed password (never store plaintext).
        is_admin (bool): Whether this user has admin panel access.
        created_at (datetime): Account creation timestamp.
        documents (relationship): Documents uploaded by this user.
        chat_history (relationship): Chat messages sent by this user.
        generated_documents (relationship): PDFs generated by this user.
    """

    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(80), unique=True, nullable=False, index=True)
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    is_admin = db.Column(db.Boolean, default=False, nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    # Relationships (cascade delete so related rows are cleaned up)
    documents = db.relationship(
        "Document", backref="owner", lazy=True, cascade="all, delete-orphan"
    )
    chat_history = db.relationship(
        "ChatHistory", backref="user", lazy=True, cascade="all, delete-orphan"
    )
    generated_documents = db.relationship(
        "GeneratedDocument", backref="creator", lazy=True, cascade="all, delete-orphan"
    )

    def set_password(self, password):
        """
        Hash and store the given plaintext password.

        Args:
            password (str): The plaintext password to hash.
        """
        self.password_hash = generate_password_hash(password)

    def check_password(self, password):
        """
        Verify a plaintext password against the stored hash.

        Args:
            password (str): The plaintext password to verify.

        Returns:
            bool: True if the password matches, False otherwise.
        """
        return check_password_hash(self.password_hash, password)

    def __repr__(self):
        return f"<User {self.username}>"


class Document(db.Model):
    """
    Represents an uploaded document (PDF or DOCX) used for RAG-based
    question answering.

    Attributes:
        id (int): Primary key.
        user_id (int): Foreign key to the uploading user.
        filename (str): Sanitized filename as stored on disk.
        original_filename (str): The original filename provided by the user.
        file_type (str): File extension/type ("pdf" or "docx").
        file_size (int): Size of the file in bytes.
        chunk_count (int): Number of text chunks created for embeddings.
        upload_date (datetime): Timestamp of upload.
        processed (bool): Whether the document has been embedded into
            the vector store successfully.
    """

    __tablename__ = "documents"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    filename = db.Column(db.String(255), nullable=False)
    original_filename = db.Column(db.String(255), nullable=False)
    file_type = db.Column(db.String(10), nullable=False)
    file_size = db.Column(db.Integer, default=0)
    chunk_count = db.Column(db.Integer, default=0)
    upload_date = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)
    processed = db.Column(db.Boolean, default=False, nullable=False)

    def __repr__(self):
        return f"<Document {self.original_filename}>"


class ChatHistory(db.Model):
    """
    Represents a single question/answer exchange in the AI chat feature.

    Attributes:
        id (int): Primary key.
        user_id (int): Foreign key to the user who asked the question.
        document_id (int): Optional foreign key to the document this
            question was scoped to (nullable for general questions).
        question (str): The user's question.
        answer (str): The AI-generated answer.
        timestamp (datetime): When the exchange occurred.
    """

    __tablename__ = "chat_history"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    document_id = db.Column(db.Integer, db.ForeignKey("documents.id"), nullable=True)
    question = db.Column(db.Text, nullable=False)
    answer = db.Column(db.Text, nullable=False)
    timestamp = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    document = db.relationship("Document", backref="chat_history", lazy=True)

    def __repr__(self):
        return f"<ChatHistory id={self.id} user_id={self.user_id}>"


class GeneratedDocument(db.Model):
    """
    Represents an AI-generated legal document (PDF) such as a Legal
    Notice, NDA, Rental Agreement, Complaint Letter, or Affidavit.

    Attributes:
        id (int): Primary key.
        user_id (int): Foreign key to the user who generated the document.
        document_type (str): Type of legal document generated.
        filename (str): Filename of the generated PDF as stored on disk.
        title (str): Human-readable title for the generated document.
        created_at (datetime): Generation timestamp.
        emailed (bool): Whether this document has been emailed.
    """

    __tablename__ = "generated_documents"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    document_type = db.Column(db.String(50), nullable=False)
    filename = db.Column(db.String(255), nullable=False)
    title = db.Column(db.String(255), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)
    emailed = db.Column(db.Boolean, default=False, nullable=False)

    def __repr__(self):
        return f"<GeneratedDocument {self.title}>"


class Advocate(db.Model):
    """
    Represents an advocate (lawyer) entry in the searchable directory.

    Attributes:
        id (int): Primary key.
        name (str): Advocate's full name.
        city (str): City where the advocate practices.
        specialization (str): Area of legal specialization.
        experience_years (int): Years of professional experience.
        phone (str): Contact phone number.
        email (str): Contact email address.
        rating (float): Average rating (0-5).
    """

    __tablename__ = "advocates"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(120), nullable=False)
    city = db.Column(db.String(80), nullable=False, index=True)
    specialization = db.Column(db.String(120), nullable=False, index=True)
    experience_years = db.Column(db.Integer, default=0)
    phone = db.Column(db.String(20), nullable=True)
    email = db.Column(db.String(120), nullable=True)
    rating = db.Column(db.Float, default=0.0)

    def __repr__(self):
        return f"<Advocate {self.name}>"


class AnalysisCache(db.Model):
    """
    Caches the result of a document analysis request, keyed by document,
    mode, and language, so repeat requests for the same combination
    return instantly instead of re-running the LLM pipeline.

    Attributes:
        id (int): Primary key.
        document_id (int): Foreign key to the analyzed document.
        mode (str): "full" or "summary".
        language (str): Language code the result was generated/translated in.
        result_json (str): The analysis result, stored as a JSON string.
        created_at (datetime): When this cache entry was created.
    """

    __tablename__ = "analysis_cache"
    __table_args__ = (
        db.UniqueConstraint(
            "document_id", "mode", "language", name="uq_analysis_cache_key"
        ),
    )

    id = db.Column(db.Integer, primary_key=True)
    document_id = db.Column(
        db.Integer, db.ForeignKey("documents.id"), nullable=False, index=True
    )
    mode = db.Column(db.String(10), nullable=False)
    language = db.Column(db.String(5), nullable=False)
    result_json = db.Column(db.Text, nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    document = db.relationship("Document", backref="analysis_cache_entries", lazy=True)

    def __repr__(self):
        return f"<AnalysisCache document_id={self.document_id} mode={self.mode} language={self.language}>"